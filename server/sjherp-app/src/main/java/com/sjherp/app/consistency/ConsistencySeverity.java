package com.sjherp.app.consistency;

/**
 * 一致性校验差异（break）的严重度（M3-T13 检查 Agent）。
 *
 * <p>口径（docs 业务文档「数据一致性校验」§4）：
 * <ul>
 *   <li>{@link #ERROR}：动了真账——恒等式破坏、应付/应收金额不符、COGS 不符、
 *       禁负库存时出现负余额。里程碑出口硬阻断项，必须清零；</li>
 *   <li>{@link #WARN}：越界或已知风险态——三单数量勾稽越界（如已开票量超过已收量）、
 *       开启负库存时出现的负余额。需关注但不一定立即阻断；</li>
 *   <li>{@link #INFO}：已知的、被配置允许的提示态（预留，本期未直接产出）。</li>
 * </ul>
 */
public enum ConsistencySeverity {
    /** 动了真账（恒等式/财务台账不符）：里程碑出口硬阻断项 */
    ERROR,
    /** 越界或已知风险态（三单数量越界 / 放行下负库存）：需关注 */
    WARN,
    /** 提示态（被配置允许的状态）：预留 */
    INFO
}
