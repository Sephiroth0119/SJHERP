package com.sjherp.domain.common;

/**
 * 档案（主数据）状态：启用 / 停用。
 *
 * <p>档案不是单据：没有"草稿→审核→执行"的生命周期，只有启停两态，
 * 因此**不**复用 {@link DocumentStatus} 状态机。停用是软性下线——
 * 历史单据仍可引用已停用档案（保证账实可追溯），但新单据不得再选用。
 *
 * <p>商品/客户/供应商/仓库等所有档案统一使用本枚举。
 */
public enum ArchiveStatus {

    /** 启用：可在新业务单据中引用 */
    ENABLED,

    /** 停用：新单据不得引用，历史数据不受影响（档案不可物理删除） */
    DISABLED
}
